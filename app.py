# === Предсказание ===
st.markdown("---")
if st.button("🎯 Определить сегмент", type="primary", use_container_width=True):
    result = predict(bundle, company)

    st.markdown("## 📊 Результат")
    col_r1, col_r2 = st.columns([1, 2])

    with col_r1:
        st.metric("Сегмент", result["segment"])
        st.metric("Уверенность", f"{result['confidence']:.1%}")
        if result["is_borderline"]:
            st.warning("⚠ Пограничный случай — модель колеблется между двумя сегментами")

    with col_r2:
        proba_df = pd.DataFrame({
            "Сегмент": list(result["probabilities"].keys()),
            "Вероятность": list(result["probabilities"].values()),
        })
        fig, ax = plt.subplots(figsize=(8, 4))
        colors = ["#2ecc71" if s == result["segment"] else "#95a5a6"
                  for s in proba_df["Сегмент"]]
        ax.barh(proba_df["Сегмент"], proba_df["Вероятность"], color=colors)
        ax.set_xlim(0, 1)
        ax.set_xlabel("Вероятность")
        ax.set_title("Распределение по сегментам")
        ax.invert_yaxis()
        for i, v in enumerate(proba_df["Вероятность"]):
            ax.text(v + 0.01, i, f"{v:.1%}", va="center")
        plt.tight_layout()
        st.pyplot(fig)

